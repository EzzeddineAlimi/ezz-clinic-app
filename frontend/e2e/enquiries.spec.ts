import { expect, test } from "@playwright/test";

test("U001 receptionist creates, closes and reopens a fictional pre-booking enquiry in FR/AR mobile", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  let patientWrites = 0;
  page.on("request", req => { if (req.method() === "POST" && /\/api\/v1\/patients$/.test(req.url())) patientWrites++; });
  await page.goto("/");
  await page.getByLabel("Code du cabinet").fill("web-fictional");
  await page.getByLabel("Identifiant personnel").fill("desk");
  await page.getByLabel("Mot de passe").fill("fictional-pass-123");
  await page.getByRole("button", { name: "Ouvrir ma session" }).click();
  await expect(page.getByRole("heading", { name: "Le fil de la journée" })).toBeVisible();
  await page.getByRole("button", { name: "Demandes", exact: true }).click();
  const marker = "Fictif-" + crypto.randomUUID().slice(0, 12);
  await page.getByLabel("Nom indiqué").fill(marker);
  await page.getByLabel("Motif administratif").fill("Demande de disponibilité");
  await page.getByLabel("Coordonnée de rappel (facultative)").fill("000-000");
  await page.getByRole("button", { name: "Ajouter à la liste" }).click();
  const entry = page.locator(".enquiry-entry").filter({ hasText: marker });
  await expect(entry).toBeVisible();
  await expect(page.getByText("Demande enregistrée, sans créer de dossier patient.")).toBeVisible();
  await expect(page.getByLabel("Nom indiqué")).toBeFocused();
  await entry.getByRole("button", { name: "Clore" }).click();
  await expect(entry).toHaveCount(0);
  await expect(page.locator(".enquiry-panel h2")).toBeFocused();
  await page.getByRole("button", { name: "Terminées" }).click();
  await expect(entry).toBeVisible();
  await page.getByRole("button", { name: "العربية", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("dir", "rtl");
  await entry.getByRole("button", { name: "إعادة فتح" }).click();
  await expect(entry).toHaveCount(0);
  await expect(page.locator(".enquiry-panel h2")).toBeFocused();
  await page.getByRole("button", { name: "قيد المتابعة" }).click();
  await expect(entry).toBeVisible();
  expect(patientWrites).toBe(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
